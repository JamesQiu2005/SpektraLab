//  CineonView.swift — the Digital Intermediate (数字中间片) read as a picture (2.2.1).
//
//  With `digital_intermediate` on, the engine replaces the paper with RFC-028's DI: the negative
//  read in printing density, its mask removed, reversed on the film's own neutral curve and written
//  as **Cineon log with ProPhoto RGB primaries** (`engine/src/core/digital_intermediate.hpp`). Every
//  other part of the app reads the engine's result as the working space, ProPhoto RGB with ROMM's
//  curve (`OutputTransform.workingSpace`). So a DI result is put through the **DI view** once, here,
//  before it is delivered: 1.x's own Cineon → ProPhoto 3D LUT (`Resources/DIView-Cineon-to-ProPhoto.cube`,
//  generated by 1.x's `CineonLUT.swift`: Kodak's Cineon decode, RFC-029's luminance shoulder that lands
//  the DI's top code 1/16 stop under white, the Oklab path to white, the ROMM encode). After it the
//  page, a strip's card, the histogram, a kept develop, a full render and an export all see a picture
//  in the working space, as for any frame, and the DI needs no second path anywhere downstream.
//
//  - **Which jobs** (`SpkEngine.wantsCineonView`): the wire's `digital_intermediate` on, `scan_film`
//    off and a negative film: exactly when the engine renders a DI (`Pipeline::di_active_`).
//  - **The lookup is the .cube's own grid, trilinear in float32**, written in the kernel rather than
//    left to the texture unit, whose filtering weights are not float32.
//  - **A new picture, the same layout.** The engine's result is RGBA16Unorm over its own buffer; the
//    view writes a buffer of its own in the same format and row pitch rules and hands that on.
//  - The kernel is compiled at run time from the source below with safe math, as `OutputTransform`'s
//    is: no `.metal` file may be in the app's target (`AGENTS.md`).

#if SPK_ENGINE
import Foundation
import Metal

final class CineonView {
    static let resourceName = "DIView-Cineon-to-ProPhoto"

    private let device: MTLDevice
    private let queue: MTLCommandQueue
    private var pipeline: MTLComputePipelineState?
    private var lut: MTLBuffer?
    private var size = 0

    init(device: MTLDevice) throws {
        self.device = device
        guard let queue = device.makeCommandQueue() else { throw EngineError.failed("no command queue for the DI view") }
        self.queue = queue
    }

    /// The picture in the working space: `pixels` read through the DI view.
    func decode(_ pixels: RenderedPixels) throws -> RenderedPixels {
        let w = pixels.size.width, h = pixels.size.height
        guard w > 0, h > 0 else { return pixels }
        let pipeline = try state()
        let lut = try table()
        let format = MTLPixelFormat.rgba16Unorm
        let align = max(1, device.minimumLinearTextureAlignment(for: format))
        let bytesPerRow = (w * 8 + align - 1) / align * align
        let length = bytesPerRow * h
        guard length <= device.maxBufferLength,
              let out = device.makeBuffer(length: length, options: .storageModeShared) else {
            throw EngineError.resource("no \(length >> 20) MB buffer for the DI view")
        }
        let descriptor = MTLTextureDescriptor.texture2DDescriptor(pixelFormat: format, width: w, height: h, mipmapped: false)
        descriptor.storageMode = .shared
        descriptor.usage = [.shaderRead]
        guard let texture = out.makeTexture(descriptor: descriptor, offset: 0, bytesPerRow: bytesPerRow),
              let commands = queue.makeCommandBuffer(), let encoder = commands.makeComputeCommandEncoder() else {
            throw EngineError.failed("the DI view's picture could not be made")
        }
        var uniforms: [UInt32] = [UInt32(bytesPerRow / 8), UInt32(size)]
        encoder.setComputePipelineState(pipeline)
        encoder.setTexture(pixels.texture, index: 0)
        encoder.setBuffer(lut, offset: 0, index: 0)
        encoder.setBuffer(out, offset: 0, index: 1)
        encoder.setBytes(&uniforms, length: uniforms.count * 4, index: 2)
        let tw = pipeline.threadExecutionWidth, th = max(1, pipeline.maxTotalThreadsPerThreadgroup / tw)
        encoder.dispatchThreadgroups(MTLSize(width: (w + tw - 1) / tw, height: (h + th - 1) / th, depth: 1),
                                     threadsPerThreadgroup: MTLSize(width: tw, height: th, depth: 1))
        encoder.endEncoding()
        commands.commit()
        commands.waitUntilCompleted()
        if let error = commands.error { throw EngineError.failed("the DI view failed: \(error.localizedDescription)") }
        var made = RenderedPixels(texture: texture, rgba16: UnsafePointer(out.contents().assumingMemoryBound(to: UInt16.self)),
                                  size: pixels.size, rowStridePixels: bytesPerRow / 8)
        made.filmGeometry = pixels.filmGeometry
        made.keep = out
        return made
    }

    // MARK: the table and the kernel

    /// The .cube's grid as float32 RGB, red fastest (the format's order), read once.
    private func table() throws -> MTLBuffer {
        if let lut { return lut }
        guard let url = Bundle.main.url(forResource: Self.resourceName, withExtension: "cube"),
              let text = try? String(contentsOf: url, encoding: .utf8) else {
            throw EngineError.failed("the DI view's table is not in this app")
        }
        let (n, values) = try Self.parse(text)
        guard let made = device.makeBuffer(bytes: values, length: values.count * 4, options: .storageModeShared) else {
            throw EngineError.failed("no buffer for the DI view's table")
        }
        size = n
        lut = made
        return made
    }

    /// `LUT_3D_SIZE n` and n³ lines of three numbers; comments, titles and domains skipped.
    static func parse(_ text: String) throws -> (size: Int, values: [Float]) {
        var n = 0
        var values: [Float] = []
        for line in text.split(whereSeparator: \.isNewline) {
            let t = line.trimmingCharacters(in: .whitespaces)
            guard let first = t.first, !t.isEmpty, first != "#" else { continue }
            if t.hasPrefix("LUT_3D_SIZE") {
                n = Int(t.split(separator: " ").last ?? "") ?? 0
                values.reserveCapacity(n * n * n * 3)
                continue
            }
            guard first.isNumber || first == "-" || first == "." else { continue }
            let parts = t.split(separator: " ", omittingEmptySubsequences: true)
            guard parts.count == 3 else { continue }
            for p in parts { values.append(Float(p) ?? 0) }
        }
        guard n >= 2, values.count == n * n * n * 3 else {
            throw EngineError.failed("the DI view's table is malformed (\(values.count / 3) entries for a grid of \(n))")
        }
        return (n, values)
    }

    private func state() throws -> MTLComputePipelineState {
        if let pipeline { return pipeline }
        let options = MTLCompileOptions()
        if #available(iOS 18.0, macCatalyst 18.0, *) {
            options.mathMode = .safe
            options.mathFloatingPointFunctions = .precise
        } else {
            options.fastMathEnabled = false
        }
        let library = try device.makeLibrary(source: Self.source, options: options)
        guard let function = library.makeFunction(name: "spkCineonView") else {
            throw EngineError.failed("the DI view's kernel is missing")
        }
        let made = try device.makeComputePipelineState(function: function)
        pipeline = made
        return made
    }

    static let source = #"""
    #include <metal_stdlib>
    using namespace metal;

    struct CineonViewUniforms {
        uint rowStride;   // the output's row pitch, in pixels
        uint n;           // the table's grid
    };

    static inline float3 lutAt(device const float *lut, uint n, uint r, uint g, uint b) {
        const uint i = 3u * (r + n * (g + n * b));
        return float3(lut[i], lut[i + 1u], lut[i + 2u]);
    }

    kernel void spkCineonView(texture2d<float, access::read> src [[texture(0)]],
                              device const float *lut [[buffer(0)]],
                              device ushort4 *dst [[buffer(1)]],
                              constant CineonViewUniforms &u [[buffer(2)]],
                              uint2 gid [[thread_position_in_grid]]) {
        if (gid.x >= src.get_width() || gid.y >= src.get_height()) return;
        const float4 c = src.read(gid);
        const float top = float(u.n - 1u);
        const float3 p = clamp(c.rgb, 0.0f, 1.0f) * top;
        const uint3 i0 = uint3(min(floor(p), float3(top - 1.0f)));
        const float3 f = p - float3(i0);
        const uint3 i1 = i0 + 1u;
        const float3 c000 = lutAt(lut, u.n, i0.x, i0.y, i0.z), c100 = lutAt(lut, u.n, i1.x, i0.y, i0.z);
        const float3 c010 = lutAt(lut, u.n, i0.x, i1.y, i0.z), c110 = lutAt(lut, u.n, i1.x, i1.y, i0.z);
        const float3 c001 = lutAt(lut, u.n, i0.x, i0.y, i1.z), c101 = lutAt(lut, u.n, i1.x, i0.y, i1.z);
        const float3 c011 = lutAt(lut, u.n, i0.x, i1.y, i1.z), c111 = lutAt(lut, u.n, i1.x, i1.y, i1.z);
        const float3 x00 = mix(c000, c100, f.x), x10 = mix(c010, c110, f.x);
        const float3 x01 = mix(c001, c101, f.x), x11 = mix(c011, c111, f.x);
        const float3 o = clamp(mix(mix(x00, x10, f.y), mix(x01, x11, f.y), f.z), 0.0f, 1.0f);
        dst[gid.y * u.rowStride + gid.x] = ushort4(ushort3(rint(o * 65535.0f)), ushort(rint(clamp(c.a, 0.0f, 1.0f) * 65535.0f)));
    }
    """#
}
#endif
